/**
 * ================================================================
 * font_digits_large.h
 * Large digit font — 12x16 pixels
 * ================================================================
 * Characters: 0-9, colon (:), hyphen (-), space
 * First char: 0x20 (space), Last char: 0x3A (colon)
 * Format: column-major, 2 bytes per column (16 rows)
 *   byte 0: rows 0-7  (LSB=top)
 *   byte 1: rows 8-15 (LSB=top)
 * Each glyph: 12 cols x 2 bytes = 24 bytes
 * Flash cost: 27 glyphs x 24 = 648 bytes
 *
 * Use this font for the main time display on the watch face.
 * At 12px wide + 1px gap = 13px per char:
 *   "12:34" = 5 chars x 13 = 65px, fits comfortably in 128px
 * ================================================================
 */

